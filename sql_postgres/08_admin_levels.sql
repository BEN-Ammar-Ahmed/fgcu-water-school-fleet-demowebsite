-- =====================================================================
-- File 08: Admin levels, activity log, who's online   PostgreSQL / Supabase
-- Four access levels for the web site (stored in wsb.app_role.role_name):
--   'Top admin'  everything, incl. confidential data (driver's licenses); manages everyone
--   'Admin'      view, add, edit, delete; manages Tier 2 people only
--   'Staff'      Tier 2 · can edit: view, add, edit; no delete
--   'Read-only'  Tier 2 · view only
-- Plus an append-only activity log (who viewed / changed / downloaded what)
-- and last-seen columns for "signed in now".
-- Run AFTER 07. Safe to re-run.
-- =====================================================================

-- 1) 'Top admin' level --------------------------------------------------
ALTER TABLE wsb.app_role DROP CONSTRAINT IF EXISTS app_role_role_name_check;
ALTER TABLE wsb.app_role ADD CONSTRAINT app_role_role_name_check
    CHECK (role_name IN ('Top admin', 'Admin', 'Staff', 'Read-only'));

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'wsb_top_admin') THEN
        CREATE ROLE wsb_top_admin NOLOGIN IN ROLE wsb_admin;
    END IF;
END $$;

INSERT INTO wsb.app_role (role_name, pg_role, description) VALUES
    ('Top admin', 'wsb_top_admin', 'Everything, including confidential data; manages all people')
ON CONFLICT (role_name) DO NOTHING;
UPDATE wsb.app_role SET description = 'Tier 2 · can edit: view, add and edit; no delete' WHERE role_name = 'Staff';
UPDATE wsb.app_role SET description = 'Tier 2 · view only' WHERE role_name = 'Read-only';
UPDATE wsb.app_role SET description = 'View, add, edit and delete; manages Tier 2 people' WHERE role_name = 'Admin';

COMMENT ON COLUMN wsb.app_user.can_see_licenses IS
    'No longer used by the web site: confidential data is for top admins (see 08_admin_levels.sql).';

-- 2) Who's online ---------------------------------------------------------
ALTER TABLE wsb.app_user ADD COLUMN IF NOT EXISTS last_seen TIMESTAMPTZ;
ALTER TABLE wsb.app_user ADD COLUMN IF NOT EXISTS last_page VARCHAR(200);

-- 3) Activity log (append-only) ------------------------------------------
CREATE TABLE IF NOT EXISTS wsb.activity_log (
    activity_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    user_id      INT REFERENCES wsb.app_user(user_id),
    username     VARCHAR(50),
    full_name    VARCHAR(100),
    kind         VARCHAR(12) NOT NULL CHECK (kind IN ('sign-in', 'view', 'change', 'download', 'access')),
    summary      TEXT NOT NULL,
    path         VARCHAR(300)
);
CREATE INDEX IF NOT EXISTS ix_activity_at   ON wsb.activity_log (at DESC);
CREATE INDEX IF NOT EXISTS ix_activity_kind ON wsb.activity_log (kind, at DESC);

-- Nobody (not even the database owner) can change or delete entries.
CREATE OR REPLACE FUNCTION wsb.activity_log_append_only()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'The activity log cannot be changed or deleted.';
END;
$$;

CREATE OR REPLACE TRIGGER trg_activity_no_update
BEFORE UPDATE OR DELETE ON wsb.activity_log
FOR EACH ROW EXECUTE FUNCTION wsb.activity_log_append_only();

CREATE OR REPLACE TRIGGER trg_activity_no_truncate
BEFORE TRUNCATE ON wsb.activity_log
FOR EACH STATEMENT EXECUTE FUNCTION wsb.activity_log_append_only();

REVOKE ALL ON FUNCTION wsb.activity_log_append_only() FROM PUBLIC;
GRANT SELECT ON wsb.activity_log TO wsb_admin;
ALTER TABLE wsb.activity_log ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS wsb_roles_all_rows ON wsb.activity_log;
CREATE POLICY wsb_roles_all_rows ON wsb.activity_log FOR SELECT TO wsb_admin USING (true);

SELECT wsb.lock_out_public_api();
