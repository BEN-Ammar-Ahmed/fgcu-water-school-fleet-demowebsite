-- =====================================================================
-- Role helpers (used by v_expiring_items so each role only sees the
-- documents it is allowed to see; the roles themselves are made in 02).
-- =====================================================================
CREATE OR REPLACE FUNCTION wsb.in_role(p_role NAME)
RETURNS BOOLEAN
LANGUAGE sql STABLE
AS $$
    SELECT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = p_role AND pg_has_role(current_user, oid, 'USAGE'))
$$;

CREATE OR REPLACE FUNCTION wsb.document_visible(p_access_level VARCHAR)
RETURNS BOOLEAN
LANGUAGE sql STABLE
AS $$
    SELECT CASE
        WHEN wsb.in_role('wsb_admin')    THEN TRUE
        WHEN wsb.in_role('wsb_staff')    THEN p_access_level IN ('General','Staff')
        WHEN wsb.in_role('wsb_readonly') THEN p_access_level = 'General'
        ELSE TRUE   -- database owner (e.g. the dashboard connection) sees everything
    END
$$;

