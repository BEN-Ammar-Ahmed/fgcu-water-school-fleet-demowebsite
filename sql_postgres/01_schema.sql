CREATE SCHEMA IF NOT EXISTS wsb;

-- ---------------------------------------------------------------------
-- Helper: Florida state fiscal year (July 1 - June 30), e.g. 'FY25-26'
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION wsb.fiscal_year(d DATE)
RETURNS VARCHAR(8)
LANGUAGE sql IMMUTABLE
AS $$
    -- fiscal year starts in July: Jan-Jun belong to the year that started last July
    SELECT 'FY' || lpad((y % 100)::text, 2, '0') || '-' || lpad(((y + 1) % 100)::text, 2, '0')
    FROM (SELECT EXTRACT(YEAR FROM d)::int - CASE WHEN EXTRACT(MONTH FROM d) >= 7 THEN 0 ELSE 1 END AS y) AS s
$$;

