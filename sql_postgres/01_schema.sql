CREATE TABLE IF NOT EXISTS wsb.driver (
    driver_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   VARCHAR(50) NOT NULL,
    last_name    VARCHAR(50) NOT NULL,
    email        VARCHAR(100) UNIQUE,
    department   VARCHAR(50),
    driver_type  VARCHAR(30) CHECK (driver_type IN ('Faculty','Staff','OPS','Other')),
    approved     BOOLEAN NOT NULL DEFAULT FALSE,
    active       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS wsb.driver_license (
    license_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id       INT NOT NULL REFERENCES wsb.driver(driver_id) ON DELETE CASCADE,
    license_number  VARCHAR(20),
    state           VARCHAR(20),
    expiration_date DATE,
    license_file    VARCHAR(255),
    verified_date   DATE,
    verified_by     VARCHAR(50)
);

-- Training / authorisation items from "FGCU_TWS_Driver_Requirements"
CREATE TABLE IF NOT EXISTS wsb.driver_qualification (
    qualification_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id          INT NOT NULL REFERENCES wsb.driver(driver_id) ON DELETE CASCADE,
    qualification_type VARCHAR(40) NOT NULL CHECK (qualification_type IN (
        'Vehicle Use Acknowledgement','FL License Check','Defensive Driving',
        'Fleet Orientation','Boater Safety Course','Vessel Practical Test',
        'Captaining Agreement','Trailer Training','Golf Cart Training','Other')),
    completed_date     DATE,
    expiration_date    DATE,
    document_location  VARCHAR(255),
    verified_by        VARCHAR(50),
    notes              TEXT
);

-- =====================================================================
-- SECTION 2: VEHICLES (boats, cars, trucks, trailers, golf carts, ATVs)
-- =====================================================================

CREATE TABLE IF NOT EXISTS wsb.vehicle (
    vehicle_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_number    VARCHAR(20) UNIQUE,
    vehicle_type    VARCHAR(30) NOT NULL CHECK (vehicle_type IN ('Boat','Car','Truck','Trailer','Golf Cart','ATV','Other')),
    make            VARCHAR(30),
    model           VARCHAR(30),
    year            INT CHECK (year BETWEEN 1950 AND 2100),
    vin             VARCHAR(30) UNIQUE,
    license_plate   VARCHAR(20),
    department      VARCHAR(50),
    wex_card_last4  CHAR(4),
    current_mileage INT CHECK (current_mileage >= 0),
    current_hours   NUMERIC(8,1) CHECK (current_hours >= 0),
    location        VARCHAR(50),
    status          VARCHAR(20) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','In Use','In Maintenance','Out of Service','Retired')),
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    notes           TEXT
);

CREATE TABLE IF NOT EXISTS wsb.vehicle_document (
    document_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id       INT NOT NULL REFERENCES wsb.vehicle(vehicle_id) ON DELETE CASCADE,
    document_type    VARCHAR(40) NOT NULL CHECK (document_type IN ('Registration','Insurance - Auto Liability',
        'Insurance - General Liability','Insurance - Workers Comp','Title','Inspection','Manual','Other')),
    file_location    VARCHAR(255) NOT NULL,
    issue_date       DATE,
    expiration_date  DATE,
    access_level     VARCHAR(10) NOT NULL DEFAULT 'General' CHECK (access_level IN ('General','Staff','Admin')),
    notes            TEXT
);

CREATE TABLE IF NOT EXISTS wsb.maintenance_rule (
    rule_id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id             INT NOT NULL REFERENCES wsb.vehicle(vehicle_id) ON DELETE CASCADE,
    maintenance_type       VARCHAR(50) NOT NULL,
    mileage_interval       INT CHECK (mileage_interval > 0),
    time_interval_months   INT CHECK (time_interval_months > 0),
    last_completed_mileage INT,
    last_completed_date    DATE,
    enabled                BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (mileage_interval IS NOT NULL OR time_interval_months IS NOT NULL)
);

-- =====================================================================
-- SECTION 3: INVOICES
-- One INVOICE = one bill/statement (WEX statement, shop invoice, P-Card purchase).
-- Each INVOICE_LINE can be tied to ONE vehicle, so a WEX statement covering
-- 10 vehicles still links every dollar to the right vehicle.
-- =====================================================================

CREATE TABLE IF NOT EXISTS wsb.invoice (
    invoice_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number       VARCHAR(40),
    -- 25, not 20 as in the SQL Server file: 'Registration/Insurance' is 22 characters
    invoice_type         VARCHAR(25) NOT NULL CHECK (invoice_type IN ('WEX Statement','Maintenance','Parts','Registration/Insurance','Other')),
    vendor               VARCHAR(80) NOT NULL,
    invoice_date         DATE NOT NULL,
    payment_due_date     DATE,
    total_amount         NUMERIC(10,2) NOT NULL,
    funding_source       VARCHAR(80),
    pcard_workday_no     VARCHAR(40),
    purchaser            VARCHAR(80),
    account_number_last4 CHAR(4),
    invoice_file         VARCHAR(255),
    fiscal_year          VARCHAR(8) GENERATED ALWAYS AS (wsb.fiscal_year(invoice_date)) STORED,
    notes                TEXT,
    created_by           VARCHAR(50) DEFAULT session_user,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (vendor, invoice_number)
);

CREATE TABLE IF NOT EXISTS wsb.invoice_line (
    line_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id    INT NOT NULL REFERENCES wsb.invoice(invoice_id) ON DELETE CASCADE,
    vehicle_id    INT REFERENCES wsb.vehicle(vehicle_id),
    line_date     DATE,
    category      VARCHAR(20) NOT NULL CHECK (category IN ('Fuel','Repair','Parts','Service','Fee','Registration','Insurance','Credit/Adjustment','Other')),
    description   TEXT,
    amount        NUMERIC(10,2) NOT NULL
);

-- WEX Purchase Activity Report code legend (AD, CL, CP ... and fee codes)
CREATE TABLE IF NOT EXISTS wsb.wex_code (
    code        VARCHAR(5) PRIMARY KEY,
    code_type   VARCHAR(12) NOT NULL CHECK (code_type IN ('Transaction','Fee')),
    meaning     VARCHAR(60) NOT NULL
);

-- =====================================================================
-- SECTION 4: ACTIVITY  (trips, fuel, maintenance)
-- =====================================================================

CREATE TABLE IF NOT EXISTS wsb.trip (
    trip_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id        INT NOT NULL REFERENCES wsb.vehicle(vehicle_id),
    driver_id         INT NOT NULL REFERENCES wsb.driver(driver_id),
    start_datetime    TIMESTAMP NOT NULL,
    end_datetime      TIMESTAMP,
    starting_mileage  INT,
    ending_mileage    INT,
    destination       VARCHAR(100),
    purpose           VARCHAR(100),
    project_program   VARCHAR(100),
    notes             TEXT,
    CHECK (end_datetime IS NULL OR end_datetime >= start_datetime),
    CHECK (ending_mileage IS NULL OR starting_mileage IS NULL OR ending_mileage >= starting_mileage)
);

CREATE TABLE IF NOT EXISTS wsb.fuel_record (
    fuel_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id       INT NOT NULL REFERENCES wsb.vehicle(vehicle_id),
    trip_id          INT REFERENCES wsb.trip(trip_id),
    invoice_line_id  INT REFERENCES wsb.invoice_line(line_id),
    fuel_date        DATE NOT NULL,
    fuel_time        TIME,
    mileage          INT,
    gallons          NUMERIC(8,3) CHECK (gallons >= 0),
    cost_per_unit    NUMERIC(7,3),
    total_cost       NUMERIC(8,2),
    other_cost       NUMERIC(8,2) DEFAULT 0,
    product          VARCHAR(20),
    vendor           VARCHAR(50),
    site_address     VARCHAR(150),
    ticket_number    VARCHAR(30),
    wex_tran_code    VARCHAR(5) REFERENCES wsb.wex_code(code),
    source           VARCHAR(20) NOT NULL DEFAULT 'Manual' CHECK (source IN ('Manual','WEX Import','Mileage Log'))
);

CREATE TABLE IF NOT EXISTS wsb.maintenance_record (
    maintenance_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id            INT NOT NULL REFERENCES wsb.vehicle(vehicle_id),
    rule_id               INT REFERENCES wsb.maintenance_rule(rule_id),
    invoice_line_id       INT REFERENCES wsb.invoice_line(line_id),
    service_date          DATE NOT NULL,
    mileage_at_service    INT,
    service_type          VARCHAR(50),
    cost                  NUMERIC(8,2),
    vendor                VARCHAR(50),
    description           TEXT,
    next_service_date     DATE,
    next_service_mileage  INT
);

