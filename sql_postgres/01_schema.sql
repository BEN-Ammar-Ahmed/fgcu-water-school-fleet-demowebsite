-- One row per changed record. record_data holds the row as JSON
-- (the new values for INSERT/UPDATE, the old values for DELETE).
CREATE TABLE IF NOT EXISTS wsb.audit_log (
    audit_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changed_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    changed_by   VARCHAR(50) NOT NULL DEFAULT session_user,
    table_name   VARCHAR(50) NOT NULL,
    action       VARCHAR(10) NOT NULL,
    record_data  JSONB
);

-- Writes the audit row. SECURITY DEFINER so Staff can be audited without being
-- allowed to touch audit_log themselves. changed_by = the login that made the change.
CREATE OR REPLACE FUNCTION wsb.trg_audit()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = wsb, pg_temp
AS $$
BEGIN
    INSERT INTO wsb.audit_log (changed_by, table_name, action, record_data)
    VALUES (session_user, TG_TABLE_NAME, TG_OP,
            CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END);
    RETURN NULL;
END;
$$;

DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['driver','driver_license','driver_qualification','vehicle','vehicle_document',
                             'invoice','invoice_line','maintenance_record','fuel_record','trip','app_user'] LOOP
        EXECUTE format('CREATE OR REPLACE TRIGGER trg_audit_%s AFTER INSERT OR UPDATE OR DELETE ON wsb.%I
                        FOR EACH ROW EXECUTE FUNCTION wsb.trg_audit()', t, t);
    END LOOP;
END $$;

-- Keep vehicle.current_mileage up to date when trips / fuel are logged
CREATE OR REPLACE FUNCTION wsb.trg_trip_mileage()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.ending_mileage IS NOT NULL THEN
        UPDATE wsb.vehicle
        SET current_mileage = NEW.ending_mileage
        WHERE vehicle_id = NEW.vehicle_id
          AND (current_mileage IS NULL OR current_mileage < NEW.ending_mileage);
    END IF;
    RETURN NULL;
END;
$$;

CREATE OR REPLACE TRIGGER trg_trip_mileage
AFTER INSERT OR UPDATE ON wsb.trip
FOR EACH ROW EXECUTE FUNCTION wsb.trg_trip_mileage();

CREATE OR REPLACE FUNCTION wsb.trg_fuel_mileage()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.mileage IS NOT NULL THEN
        UPDATE wsb.vehicle
        SET current_mileage = NEW.mileage
        WHERE vehicle_id = NEW.vehicle_id
          AND (current_mileage IS NULL OR current_mileage < NEW.mileage);
    END IF;
    RETURN NULL;
END;
$$;

CREATE OR REPLACE TRIGGER trg_fuel_mileage
AFTER INSERT OR UPDATE ON wsb.fuel_record
FOR EACH ROW EXECUTE FUNCTION wsb.trg_fuel_mileage();

